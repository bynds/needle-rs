static int is_ascii_ws(unsigned char b) {
  return b == ' ' || b == '\t' || b == '\n' || b == 0x0C || b == '\r';
}

/* json_find_matching */
static size_t json_find_matching(slice s, size_t start, unsigned char open, unsigned char close) {
  size_t depth = 0, i = start;
  int in_str = 0, escape = 0;
  while (i < s.n) {
    unsigned char b = s.p[i];
    if (in_str) {
      if (escape)
        escape = 0;
      else if (b == '\\')
        escape = 1;
      else if (b == '"')
        in_str = 0;
    } else if (b == '"') {
      in_str = 1;
    } else if (b == open) {
      depth += 1;
    } else if (b == close) {
      depth = depth ? depth - 1 : 0;
      if (depth == 0) return i;
    }
    i += 1;
  }
  return s.n ? s.n - 1 : 0;
}

