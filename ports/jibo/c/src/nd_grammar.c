static int utf8_valid(const unsigned char *s, size_t n) {
  size_t i = 0;
  while (i < n) {
    unsigned c = s[i];
    if (c < 0x80u) {
      i++;
    } else if (c >= 0xC2u && c <= 0xDFu) {
      if (n - i < 2 || (s[i + 1] & 0xC0u) != 0x80u) return 0;
      i += 2;
    } else if (c >= 0xE0u && c <= 0xEFu) {
      unsigned c1;
      if (n - i < 3) return 0;
      c1 = s[i + 1];
      if (c == 0xE0u && (c1 < 0xA0u || c1 > 0xBFu)) return 0;
      if (c == 0xEDu && (c1 < 0x80u || c1 > 0x9Fu)) return 0;
      if ((c1 & 0xC0u) != 0x80u || (s[i + 2] & 0xC0u) != 0x80u) return 0;
      i += 3;
    } else if (c >= 0xF0u && c <= 0xF4u) {
      unsigned c1;
      if (n - i < 4) return 0;
      c1 = s[i + 1];
      if (c == 0xF0u && (c1 < 0x90u || c1 > 0xBFu)) return 0;
      if (c == 0xF4u && (c1 < 0x80u || c1 > 0x8Fu)) return 0;
      if ((c1 & 0xC0u) != 0x80u || (s[i + 2] & 0xC0u) != 0x80u || (s[i + 3] & 0xC0u) != 0x80u)
        return 0;
      i += 4;
    } else {
      return 0;
    }
  }
  return 1;
}

/* Decode one scalar from valid UTF-8 at s[0..n), n > 0. */
static uint32_t utf8_decode(const unsigned char *s, size_t n, size_t *adv) {
  unsigned c = s[0];
  if (c < 0x80u || n < 2) {
    *adv = 1;
    return c;
  }
  if (c < 0xE0u) {
    *adv = 2;
    return ((uint32_t)(c & 0x1Fu) << 6) | (s[1] & 0x3Fu);
  }
  if (c < 0xF0u || n < 4) {
    *adv = 3;
    return ((uint32_t)(c & 0x0Fu) << 12) | ((uint32_t)(s[1] & 0x3Fu) << 6) | (s[2] & 0x3Fu);
  }
  *adv = 4;
  return ((uint32_t)(c & 0x07u) << 18) | ((uint32_t)(s[1] & 0x3Fu) << 12) |
         ((uint32_t)(s[2] & 0x3Fu) << 6) | (s[3] & 0x3Fu);
}

static size_t utf8_encode(uint32_t cp, unsigned char *b) {
  if (cp < 0x80u) {
    b[0] = (unsigned char)cp;
    return 1;
  }
  if (cp < 0x800u) {
    b[0] = (unsigned char)(0xC0u | (cp >> 6));
    b[1] = (unsigned char)(0x80u | (cp & 0x3Fu));
    return 2;
  }
  if (cp < 0x10000u) {
    b[0] = (unsigned char)(0xE0u | (cp >> 12));
    b[1] = (unsigned char)(0x80u | ((cp >> 6) & 0x3Fu));
    b[2] = (unsigned char)(0x80u | (cp & 0x3Fu));
    return 3;
  }
  b[0] = (unsigned char)(0xF0u | (cp >> 18));
  b[1] = (unsigned char)(0x80u | ((cp >> 12) & 0x3Fu));
  b[2] = (unsigned char)(0x80u | ((cp >> 6) & 0x3Fu));
  b[3] = (unsigned char)(0x80u | (cp & 0x3Fu));
  return 4;
}

/* A growable byte buffer. */
typedef struct {
  unsigned char *p;
  size_t n, c;
} bbuf;

static int bb_reserve(bbuf *b, size_t extra) {
  size_t need, nc;
  unsigned char *q;
  if (!nd_add_ok(b->n, extra, &need) || !nd_add_ok(need, 1, &need)) return ND_E_NOMEM;
  if (need <= b->c) return 0;
  nc = b->c ? b->c : 32u;
  while (nc < need) {
    if (!nd_mul_ok(nc, 2, &nc)) return ND_E_NOMEM;
  }
  q = (unsigned char *)realloc(b->p, nc);
  if (!q) return ND_E_NOMEM;
  b->p = q;
  b->c = nc;
  return 0;
}

static int bb_add(bbuf *b, const void *s, size_t n) {
  if (bb_reserve(b, n)) return ND_E_NOMEM;
  if (n) memcpy(b->p + b->n, s, n);
  b->n += n;
  b->p[b->n] = 0;
  return 0;
}

static char *dup_bytes(const void *s, size_t n) {
  size_t m;
  char *d;
  if (!nd_add_ok(n, 1, &m)) return NULL;
  d = (char *)malloc(m);
  if (!d) return NULL;
  if (n) memcpy(d, s, n);
  d[n] = 0;
  return d;
}

/* String::from_utf8_lossy: each maximal invalid subsequence (Utf8Chunks) becomes U+FFFD. */
static int lossy_utf8(const unsigned char *s, size_t n, bbuf *out) {
  static const unsigned char fffd[3] = {0xEF, 0xBF, 0xBD};
  size_t i = 0;
  out->n = 0;
  if (bb_reserve(out, 0)) return ND_E_NOMEM;
  out->p[0] = 0;
  while (i < n) {
    unsigned c = s[i];
    size_t need = 0, k;
    unsigned lo = 0x80u, hi = 0xBFu;
    if (c < 0x80u) {
      if (bb_add(out, s + i, 1)) return ND_E_NOMEM;
      i++;
      continue;
    }
    if (c >= 0xC2u && c <= 0xDFu) {
      need = 1;
    } else if (c >= 0xE0u && c <= 0xEFu) {
      need = 2;
      if (c == 0xE0u) lo = 0xA0u;
      if (c == 0xEDu) hi = 0x9Fu;
    } else if (c >= 0xF0u && c <= 0xF4u) {
      need = 3;
      if (c == 0xF0u) lo = 0x90u;
      if (c == 0xF4u) hi = 0x8Fu;
    }
    if (need == 0) {
      if (bb_add(out, fffd, 3)) return ND_E_NOMEM;
      i++;
      continue;
    }
    /* how many bytes of a valid sequence follow */
    for (k = 1; k <= need; k++) {
      unsigned b;
      if (i + k >= n) break;
      b = s[i + k];
      if (k == 1) {
        if (b < lo || b > hi) break;
      } else if ((b & 0xC0u) != 0x80u) {
        break;
      }
    }
    if (k > need) {
      if (bb_add(out, s + i, need + 1)) return ND_E_NOMEM;
      i += need + 1;
    } else {
      if (bb_add(out, fffd, 3)) return ND_E_NOMEM;
      i += k;
    }
  }
  return 0;
}

