static unsigned uprops(uint32_t cp) {
  size_t lo = 0, hi = sizeof UPROPS / sizeof UPROPS[0];
  if (cp < 0x80u) {
    unsigned f = 0;
    if ((cp >= '0' && cp <= '9') || (cp >= 'a' && cp <= 'z') || (cp >= 'A' && cp <= 'Z')) f |= UP_ALNUM;
    if (cp >= 'A' && cp <= 'Z') f |= UP_UPPER;
    if (cp >= 'a' && cp <= 'z') f |= UP_LOWER;
    return f;
  }
  while (lo < hi) {
    size_t mid = lo + (hi - lo) / 2;
    if (cp < UPROPS[mid].lo)
      hi = mid;
    else if (cp > UPROPS[mid].hi)
      lo = mid + 1;
    else
      return UPROPS[mid].f;
  }
  return 0;
}

/* tokenizer::to_snake_case. `name` is valid UTF-8. */
static int grammar_snake_case(const char *name, size_t len, char **out, size_t *out_len) {
  uint32_t *chars;
  size_t n = 0, i = 0;
  bbuf o = {0, 0, 0};
  int prev_underscore = 0, prev_upper = 0;
  chars = (uint32_t *)nd_calloc(len, sizeof *chars);
  if (!chars) return ND_E_NOMEM;
  while (i < len) {
    size_t adv;
    chars[n++] = utf8_decode((const unsigned char *)name + i, len - i, &adv);
    i += adv;
  }
  if (bb_reserve(&o, len + 4u)) {
    free(chars);
    return ND_E_NOMEM;
  }
  o.p[0] = 0;
  for (i = 0; i < n; i++) {
    uint32_t c = chars[i];
    unsigned f = uprops(c);
    if ((f & UP_ALNUM) || c == '_') {
      if (c == '_') {
        if (!prev_underscore && o.n != 0) {
          if (bb_add(&o, "_", 1)) goto oom;
          prev_underscore = 1;
        }
        prev_upper = 0;
      } else if (f & UP_UPPER) {
        int prev_lower = i > 0 && ((uprops(chars[i - 1]) & UP_LOWER) ||
                                   (chars[i - 1] >= '0' && chars[i - 1] <= '9'));
        int next_lower = i + 1 < n && (uprops(chars[i + 1]) & UP_LOWER);
        unsigned char b[4];
        uint32_t lc = (c >= 'A' && c <= 'Z') ? c + 32u : c; /* to_ascii_lowercase */
        if (i > 0 && !prev_underscore && (prev_lower || (prev_upper && next_lower))) {
          if (bb_add(&o, "_", 1)) goto oom;
        }
        if (bb_add(&o, b, utf8_encode(lc, b))) goto oom;
        prev_underscore = 0;
        prev_upper = 1;
      } else {
        unsigned char b[4];
        if (bb_add(&o, b, utf8_encode(c, b))) goto oom;
        prev_underscore = 0;
        prev_upper = 0;
      }
    } else {
      if (!prev_underscore && o.n != 0) {
        if (bb_add(&o, "_", 1)) goto oom;
        prev_underscore = 1;
      }
      prev_upper = 0;
    }
  }
  while (o.n > 0 && o.p[o.n - 1] == '_') o.n--;
  o.p[o.n] = 0;
  free(chars);
  *out = (char *)o.p;
  *out_len = o.n;
  return 0;
oom:
  free(chars);
  free(o.p);
  return ND_E_NOMEM;
}

