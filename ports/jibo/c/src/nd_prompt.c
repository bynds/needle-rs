/* ---- build_prompt / compact_json -------------------------------------------------------- */

char *nd_compact_json(const char *s) {
  size_t n, o = 0, i;
  int in_string = 0, escaped = 0;
  char *out;
  if (!s) return NULL;
  n = strlen(s);
  if (n == (size_t)-1) return NULL;
  out = (char *)malloc(n + 1);
  if (!out) return NULL;
  /* Rust walks chars, but every test is against an ASCII char, and in UTF-8 no byte of a
   * multi-byte char is ASCII, so walking bytes is the same. */
  for (i = 0; i < n; i++) {
    char c = s[i];
    if (in_string) {
      out[o++] = c;
      if (escaped)
        escaped = 0;
      else if (c == '\\')
        escaped = 1;
      else if (c == '"')
        in_string = 0;
      continue;
    }
    switch (c) {
      case '"':
        in_string = 1;
        out[o++] = c;
        break;
      case ' ':
      case '\t':
      case '\n':
      case '\r':
        break;
      default:
        out[o++] = c;
        break;
    }
  }
  out[o] = '\0';
  return out;
}

char *nd_build_prompt(const char *query, const char *tools_json, const char *system_or_null) {
  const char *parts[16];
  size_t np = 0, total = 0, i, o = 0;
  char *tools, *out;
  if (!query || !tools_json) return NULL;
  tools = nd_compact_json(tools_json);
  if (!tools) return NULL;
  if (system_or_null) {
    parts[np++] = ND_IM_START;
    parts[np++] = "system\n";
    parts[np++] = system_or_null;
    parts[np++] = ND_IM_END;
    parts[np++] = "\n";
  }
  parts[np++] = ND_IM_START;
  parts[np++] = "user\n";
  parts[np++] = ND_TOOLS_START;
  parts[np++] = tools;
  parts[np++] = ND_TOOLS_END;
  parts[np++] = "\n";
  parts[np++] = query;
  parts[np++] = ND_IM_END;
  parts[np++] = "\n";
  parts[np++] = ND_IM_START;
  parts[np++] = "assistant\n";
  for (i = 0; i < np; i++) {
    if (!nd_add_ok(total, strlen(parts[i]), &total)) {
      free(tools);
      return NULL;
    }
  }
  if (!nd_add_ok(total, 1, &total) || !(out = (char *)malloc(total))) {
    free(tools);
    return NULL;
  }
  for (i = 0; i < np; i++) {
    size_t l = strlen(parts[i]);
    memcpy(out + o, parts[i], l);
    o += l;
  }
  out[o] = '\0';
  free(tools);
  return out;
}

